function createTurmaVinculo(
  turmaId: string,
  present: number,
  absent: number,
  avgDist: number
): AlunoTurma {
  const base = TURMAS_CATALOG[turmaId];
  const total = present + absent;
  const rate = total > 0 ? present / total : 1.0;
  return {
    ...base,
    total_sessions: total,
    total_present: present,
    total_absent: absent,
    attendance_rate: rate,
    avg_distance_meters: avgDist,
    status: rate < 0.75 ? "at_risk" : "regular",
  };
}

